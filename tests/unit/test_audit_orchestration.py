@pytest.mark.parametrize("status", ["ACCEPTED", "FAILED", "UNKNOWN", "RETRYABLE"])
def test_delivery_outcomes_and_no_blind_retries(fixture, configured, status):
    box, draft = notice(fixture)
    transport = Transport(
        Outcome(
            status,
            "SIMULATED",
            42 if status == "ACCEPTED" else None,
            3600 if status == "RETRYABLE" else None,
        )
    )
    result = box.send(draft["notification_id"], transport=transport)
    assert result["status"] == status
    assert box.send(draft["notification_id"], transport=transport)["status"] == status
    assert transport.calls == 1
    if status == "RETRYABLE":
        assert box.send(draft["notification_id"], retry=True, transport=transport)["blocked"]
    if status == "UNKNOWN":
        assert (
            box.send(draft["notification_id"], retry=True, transport=transport)["status"]
            == "UNKNOWN"
        )
        result = box.reconcile(
            draft["notification_id"],
            outcome="accepted",
            reason="simulated verified service receipt",
            message_id=42,
            confirm_stopped=True,
        )
        assert result["status"] == "ACCEPTED" and result["message_id"] == 42


