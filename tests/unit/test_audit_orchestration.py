class Response(io.BytesIO):
    def __enter__(self):
        return self

    def __exit__(self, *args):
        self.close()


class Opener:
    def __init__(self, response):
        self.response = response

    def open(self, request, timeout):
        assert timeout == 10
        if request.full_url.endswith("getChat"):
            return Response(b'{"ok":true,"result":{"id":12345,"type":"private"}}')
        if isinstance(self.response, Exception):
            raise self.response
        return Response(json.dumps(self.response).encode())


@pytest.mark.parametrize(
    "payload,expected",
    [
        ({"ok": True, "result": {"message_id": 5, "chat": {"id": 12345}}}, "ACCEPTED"),
        ({"ok": False, "error_code": 403}, "FAILED"),
        ({"ok": False, "error_code": 429, "parameters": {"retry_after": 172800}}, "RETRYABLE"),
        ({"ok": False, "error_code": 500}, "UNKNOWN"),
        ({}, "UNKNOWN"),
        (TimeoutError("https://api.telegram.org/bot123:SIMULATED_SECRET/sendMessage"), "UNKNOWN"),
    ],
)
def test_safe_telegram_transport(configured, payload, expected, capsys):
    result = TelegramTransport(Opener(payload)).send("simulated")
    assert result.status == expected
