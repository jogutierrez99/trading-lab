def test_openai_transport_posts_once_with_strict_schema(monkeypatch, tmp_path):
    from trading_lab_orchestration import audit_openai
    from trading_lab_orchestration.processes import safe_environment

    env = tmp_path / ".env"
    env.write_text("OTHER='unclosed\nOPENAI_API_KEY='fake-local' # comment\n")
