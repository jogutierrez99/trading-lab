def test_concurrent_audits_from_two_processes(fixture):
    request_file = fixture.root.parent / "audit-request.json"
    request_file.write_text(fixture.request.model_dump_json(), encoding="utf-8")
    args = [
        sys.executable,
        "-B",
        str(ROOT / "scripts/orchestrator.py"),
        "--db",
        str(fixture.store.path),
        "audit",
        str(request_file),
        "--artifacts",
        str(fixture.output),
    ]
    env = os.environ.copy()
    env["PYTHONPATH"] = str(ROOT / "src")
    processes = [
        subprocess.Popen(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env)
        for _ in range(2)
    ]
    for process in processes:
        stdout, stderr = process.communicate(timeout=30)
        # This intentionally incomplete fixture lacks source seals in a fresh
        # process: it must block evidence, or report a concurrent coordinator.
        assert process.returncode == 2
        payload = json.loads(stdout)
        assert payload.get("status") == "BLOCKED_EVIDENCE" or payload.get("error") == "ValueError"
        assert b"Traceback" not in stderr and b"database is locked" not in stdout
    with fixture.store.connection() as conn:
        assert conn.execute("SELECT COUNT(*) FROM audits").fetchone()[0] == 1
    assert len(list(fixture.output.glob("audit_*"))) == 1


